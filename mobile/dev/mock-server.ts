const EXAMPLES =
  'Examples: "in 2 hours", "tomorrow at 9:00", "friday at 14:30", "2026-11-20 09:00", "every weekday at 9:00", "every monday at 8am", "every 2 hours".';
const DAYS = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];

function nextDaily(days: number[], hour: number, minute: number, from: number): number {
  const d = new Date(from);
  d.setSeconds(0, 0);
  d.setHours(hour, minute);
  for (let i = 0; i < 8; i++) {
    if (days.includes(d.getDay()) && d.getTime() > from) return d.getTime();
    d.setDate(d.getDate() + 1);
  }
  return d.getTime();
}

const MONTH_WORDS = [
  'january',
  'february',
  'march',
  'april',
  'may',
  'june',
  'july',
  'august',
  'september',
  'october',
  'november',
  'december',
];
const NTH: Record<string, number> = { first: 1, second: 2, third: 3, fourth: 4, last: -1 };

/** The date `on` names in a month (`schedule::month_day`): a date it lacks is its last day. */
function monthDayIn(year: number, month0: number, on: MonthDay): Date {
  const last = new Date(year, month0 + 1, 0).getDate();
  if ('day' in on) return new Date(year, month0, on.day < 0 ? last : Math.min(on.day, last));
  if (on.nth < 0) {
    const end = new Date(year, month0, last);
    return new Date(year, month0, last - ((end.getDay() - on.weekday + 7) % 7));
  }
  const first = new Date(year, month0, 1).getDay();
  return new Date(year, month0, 1 + ((on.weekday - first + 7) % 7) + 7 * (on.nth - 1));
}

/** `schedule::next_monthly`, on this machine's clock: the first run after `from`. */
function nextMonthly(
  months: number,
  on: MonthDay,
  hour: number,
  minute: number,
  from: number,
  start?: number
): number {
  const now = new Date(from);
  let index = now.getFullYear() * 12 + now.getMonth();
  if (start !== undefined) index += (start - now.getMonth() + 12) % 12;
  const step = start === undefined ? 1 : months;
  for (let i = 0; i < 3; i++, index += step) {
    const d = monthDayIn(Math.floor(index / 12), index % 12, on);
    d.setHours(hour, minute, 0, 0);
    if (d.getTime() > from) return d.getTime();
  }
  return from;
}

function clock(text: string): [number, number] | null {
  const m = /^(\d{1,2})(?::(\d{2}))?\s*(am|pm)?$/.exec(text.trim());
  if (!m) return null;
  let h = Number(m[1]);
  if (m[3] === 'pm' && h < 12) h += 12;
  if (m[3] === 'am' && h === 12) h = 0;
  return h < 24 ? [h, Number(m[2] ?? 0)] : null;
}

/** A small slice of `schedule::parse`, enough to drive the phone's composer. */
function parseWhen(
  raw: string,
  now: number
): { nextAt: number; repeat?: Repeat } | { error: string } {
  const s = raw.trim().toLowerCase();
  const fail = (why: string) => ({ error: `${why} ${EXAMPLES}` });
  if (!s) return fail('Say when.');
  let m = /^every (\d+ )?(minute|min|hour)s?$/.exec(s);
  if (m) {
    const n = Number(m[1] ?? 1);
    const minutes = m[2] === 'hour' ? n * 60 : n;
    if (minutes < 15) return fail('Routines can repeat every 15 minutes at most.');
    return { nextAt: now + minutes * 60_000, repeat: { kind: 'every', minutes } };
  }
  // "every monday and thursday at 08:30", as the picker writes several days.
  m =
    /^every (day|weekday|weekend day|[a-z]+days?(?:(?:,| and|, and) [a-z]+days?)*) (?:at )?(.+)$/.exec(
      s
    );
  if (m) {
    const t = clock(m[2]);
    if (!t) return fail(`I can't read "${m[2]}" as a time.`);
    const days =
      m[1] === 'day'
        ? [0, 1, 2, 3, 4, 5, 6]
        : m[1] === 'weekday'
          ? [1, 2, 3, 4, 5]
          : m[1] === 'weekend day'
            ? [0, 6]
            : m[1].split(/,? and |, /).map((d) => DAYS.indexOf(d.replace(/s$/, '')));
    const unknown = days.indexOf(-1);
    if (unknown !== -1) return fail(`"${m[1]}" has a day I don't know.`);
    return {
      nextAt: nextDaily(days, t[0], t[1], now),
      repeat: { kind: 'days', days, hour: t[0], minute: t[1] },
    };
  }
  // "every 3 months on the last friday at 16:00 starting january", as the picker writes it.
  m =
    /^every (month|(\d+) months) on the (?:(\d+)(?:st|nd|rd|th)|(last) day|(first|second|third|fourth|last) ([a-z]+day)) at (\d{1,2}):(\d{2})(?: starting ([a-z]+))?$/.exec(
      s
    );
  if (m) {
    const months = m[2] ? Number(m[2]) : 1;
    if (months > 12) return fail('That’s too far apart for a routine: every 12 months at most.');
    const on: MonthDay = m[6]
      ? { nth: NTH[m[5]], weekday: DAYS.indexOf(m[6]) }
      : { day: m[4] ? -1 : Number(m[3]) };
    if ('day' in on && on.day > 31) return fail('A month has at most 31 days.');
    if ('weekday' in on && on.weekday === -1) return fail(`"${m[6]}" isn't a day I know.`);
    const start = m[9] ? MONTH_WORDS.indexOf(m[9]) : undefined;
    const [hour, minute] = [Number(m[7]), Number(m[8])];
    const nextAt = nextMonthly(months, on, hour, minute, now, start === -1 ? undefined : start);
    const first = new Date(nextAt);
    const from = months > 1 ? first.getFullYear() * 12 + first.getMonth() : undefined;
    return {
      nextAt,
      repeat: { kind: 'monthly', months, on, hour, minute, ...(from !== undefined && { from }) },
    };
  }
  // "2026-11-20 09:00", local: a once on a date, as the picker writes it.
  m = /^(\d{4})-(\d{2})-(\d{2})\s+(\d{1,2}):(\d{2})$/.exec(s);
  if (m) {
    const at = new Date(+m[1], +m[2] - 1, +m[3], +m[4], +m[5]).getTime();
    if (at <= now) return fail('That time has passed.');
    return { nextAt: at };
  }
  m = /^in (\d+) (minute|min|hour|day)s?$/.exec(s);
  if (m) {
    const unit = { minute: 60_000, min: 60_000, hour: 3_600_000, day: 86_400_000 }[m[2]]!;
    return { nextAt: now + Number(m[1]) * unit };
  }
  m = /^(today|tomorrow|[a-z]+day)?\s*(?:at )?(.+)$/.exec(s);
  const t = m ? clock(m[2]) : null;
  if (m && t) {
    const d = new Date(now);
    d.setSeconds(0, 0);
    d.setHours(t[0], t[1]);
    if (m[1] === 'tomorrow') d.setDate(d.getDate() + 1);
    else if (m[1] && m[1] !== 'today') {
      const day = DAYS.indexOf(m[1]);
      if (day === -1) return fail(`I can't read "${m[1]}" as a day.`);
      while (d.getDay() !== day || d.getTime() <= now) d.setDate(d.getDate() + 1);
    } else if (d.getTime() <= now) d.setDate(d.getDate() + 1);
    return { nextAt: d.getTime() };
  }
  return fail(`I can't read "${raw.trim()}" as a time.`);
}
