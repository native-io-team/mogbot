  /** The device behind `Authorization: Bearer`, if it's paired and not removed. */
  function bearer(req: http.IncomingMessage): string | null {
    const token = /^Bearer (.+)$/.exec(req.headers.authorization ?? '')?.[1];
    const entry = token ? [...devices.values()].find((d) => d.token === token) : undefined;
    return entry && !entry.revoked ? entry.device.id : null;
  }

  /** The blob and attachment routes. True when it answered. */
  async function files_(req: http.IncomingMessage, res: http.ServerResponse): Promise<boolean> {
    const url = new URL(req.url ?? '/', 'http://mock');
    const isBlob =
      url.pathname === HTTP.uploadBlob || url.pathname.startsWith(`${HTTP.uploadBlob}/`);
    const attachment = /^\/v1\/agents\/([^/]+)\/attachments\/(.+)$/.exec(url.pathname);
    if (!isBlob && !attachment) return false;
    const deviceId = bearer(req);
    if (!deviceId) {
      res.writeHead(401).end();
      return true;
    }
    if (req.method === 'PUT' && url.pathname === HTTP.uploadBlob) {
      // Read to the end even when it's too big, so the phone hears 413
      // rather than a connection reset halfway through its upload.
      const bytes = await readBytes(req, MAX_ATTACHMENT_BYTES);
      if (!bytes) {
        res.writeHead(413, { Connection: 'close' }).end();
        return true;
      }
      const name = decodeURIComponent(String(req.headers['x-name'] ?? 'file')) || 'file';
      const ref: BlobRef = {
        blobId: `blob_${randomUUID().slice(0, 12)}`,
        name,
        mime: String(req.headers['content-type'] ?? 'application/octet-stream'),
        size: bytes.length,
      };
      blobs.set(ref.blobId, { ...ref, bytes, deviceId, expiresAt: Date.now() + BLOB_TTL_MS });
      res.writeHead(200, { 'Content-Type': 'application/json' }).end(JSON.stringify(ref));
      return true;
    }
    if (req.method !== 'GET') {
      res.writeHead(404).end();
      return true;
    }
    // The Mac's route: the attachment's own path (`attachments/<id>/<name>`)
    // under the agent. A doubled `attachments/attachments/…` (what phone
    // builds before this fix asked for) is read the same way, as the Mac does.
    const rest = attachment?.[2].replace(/^attachments\//, '');
    const found = attachment
      ? files.get(
          `${decodeURIComponent(attachment[1])}:attachments/${rest!
            .split('/')
            .map(decodeURIComponent)
            .join('/')}`
        )
      : (() => {
          const b = blobs.get(decodeURIComponent(url.pathname.split('/').pop()!));
          return b && b.deviceId === deviceId ? b : undefined;
        })();
    if (!found) {
      res.writeHead(404).end();
      return true;
    }
    // `?w=` asks for a thumbnail; the mock has no image library, so it
    // sends the original, which the phone scales down just the same.
    res
      .writeHead(200, {
        'Content-Type': found.mime,
        'Content-Length': found.bytes.length,
        'Cache-Control': 'private, max-age=86400',
      })
      .end(found.bytes);
    return true;
  }

