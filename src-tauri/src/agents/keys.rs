//! Agent keys (docs/design/agent-keys.md): every agent is a keycap with a
//! colourway, a legend (an icon) and a keyboard key it's bound to. This holds
//! the ids, fills them in for agents saved before keys existed, keeps bound
//! keys unique, and checks a change from chat or a client.
//!
//! The data is the shared `agent-keys.json` the clients read too
//! (`packages/companion-protocol/src/agentKeys.ts`), so the Mac's migration
//! and a client's fallback land on the same key; `agent-key-cases.json` holds
//! both to the same answers.

use serde::Deserialize;
use std::collections::{HashMap, HashSet};
use std::sync::LazyLock;

use super::store::Agent;

#[derive(Deserialize)]
struct Colorway {
    id: String,
    name: String,
    legacy: String,
}

#[derive(Deserialize)]
struct Icon {
    id: String,
    name: String,
    /// Other names a search finds it by ("logo" for the app's mark).
    #[serde(default)]
    aka: Vec<String>,
}

#[derive(Deserialize)]
struct Rule {
    icon: String,
    words: Vec<String>,
}

#[derive(Deserialize)]
struct PackInfo {
    prefix: String,
    count: usize,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Spec {
    colorways: Vec<Colorway>,
    legacy_colors: HashMap<String, String>,
    icons: Vec<Icon>,
    chief_icon: String,
    chief_colorway: String,
    default_icon: String,
    icon_rules: Vec<Rule>,
    key_chars: String,
    pack: PackInfo,
    icon_synonyms: HashMap<String, Vec<String>>,
}

static SPEC: LazyLock<Spec> = LazyLock::new(|| {
    serde_json::from_str(include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../packages/companion-protocol/src/agent-keys.json"
    )))
    .expect("agent-keys.json is the shared spec")
});

/// The icon pack's index (`agent-key-pack/index.json`, generated by
/// `scripts/agent-key-pack.mjs` from Lucide): every icon's name, tags and
/// categories. The Mac accepts exactly these ids and searches them.
#[derive(Deserialize)]
struct PackIndex {
    icons: Vec<(String, String, Vec<usize>)>,
}

/// One icon as the search sees it (`IconEntry` in agentKeySearch.ts).
struct Entry {
    id: String,
    featured: bool,
    name_words: Vec<String>,
    tag_words: Vec<String>,
}

struct Pack {
    ids: HashSet<String>,
    /// The featured legends first, then the pack in its order.
    entries: Vec<Entry>,
    synonyms: HashMap<String, Vec<String>>,
}

static PACK: LazyLock<Pack> = LazyLock::new(|| {
    let index: PackIndex = serde_json::from_str(include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../packages/companion-protocol/src/agent-key-pack/index.json"
    )))
    .expect("agent-key-pack/index.json is the shared pack");
    let mut entries: Vec<Entry> = SPEC
        .icons
        .iter()
        .map(|i| Entry {
            id: i.id.clone(),
            featured: true,
            name_words: unique(
                words_stemmed(&i.name)
                    .into_iter()
                    .chain(words_stemmed(&i.id))
                    .chain(i.aka.iter().flat_map(|w| words_stemmed(w))),
            ),
            tag_words: unique(
                SPEC.icon_rules
                    .iter()
                    .filter(|r| r.icon == i.id)
                    .flat_map(|r| r.words.iter().map(|w| stem(w))),
            ),
        })
        .collect();
    let mut ids = HashSet::new();
    for (name, tags, _) in &index.icons {
        let id = format!("{}{name}", SPEC.pack.prefix);
        ids.insert(id.clone());
        entries.push(Entry {
            id,
            featured: false,
            name_words: words_stemmed(name),
            tag_words: unique(tags.split(',').flat_map(words_stemmed)),
        });
    }
    let synonyms = SPEC
        .icon_synonyms
        .iter()
        .map(|(k, v)| (stem(k), v.iter().map(|s| stem(s)).collect()))
        .collect();
    Pack {
        ids,
        entries,
        synonyms,
    }
});

pub fn colorways() -> Vec<&'static str> {
    SPEC.colorways.iter().map(|c| c.id.as_str()).collect()
}

/// The featured legends: the defaults, and what a new agent is given.
pub fn icons() -> Vec<&'static str> {
    SPEC.icons.iter().map(|i| i.id.as_str()).collect()
}

/// What a tool's `icon` takes, for its schema.
pub fn icon_hint() -> String {
    format!(
        "One of the featured legends ({}), any of the {} icons in the pack as \"{}<name>\" (\"{}wallet\", \"{}house\"), or a word for what it's for (\"invoice\", \"dog\", \"calendar\"): the best match is used.",
        icons().join(", "),
        SPEC.pack.count,
        SPEC.pack.prefix,
        SPEC.pack.prefix,
        SPEC.pack.prefix
    )
}

/// How many icons the pack has (agent-keys.json's `pack.count`, checked against the index).
pub fn pack_count() -> (usize, usize) {
    (SPEC.pack.count, PACK.ids.len())
}

pub fn is_colorway(id: &str) -> bool {
    SPEC.colorways.iter().any(|c| c.id == id)
}

/// A featured legend or an icon in the pack (`lucide:wallet`).
pub fn is_icon(id: &str) -> bool {
    SPEC.icons.iter().any(|i| i.id == id) || PACK.ids.contains(id)
}

fn unique(words: impl IntoIterator<Item = String>) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for w in words {
        if !out.contains(&w) {
            out.push(w);
        }
    }
    out
}

/// "Invoices" → "invoice"; "batteries" → "battery" (`iconStem` in agentKeySearch.ts).
fn stem(word: &str) -> String {
    let w = word.to_lowercase();
    if w.len() > 4 && w.ends_with("ies") {
        return format!("{}y", &w[..w.len() - 3]);
    }
    if w.len() > 3 && w.ends_with('s') && !w.ends_with("ss") {
        return w[..w.len() - 1].to_string();
    }
    w
}

fn words_stemmed(text: &str) -> Vec<String> {
    words(text).iter().map(|w| stem(w)).collect()
}

/// One typo apart: a letter added, dropped, changed, or two swapped.
fn one_edit(a: &str, b: &str) -> bool {
    let (a, b): (Vec<char>, Vec<char>) = (a.chars().collect(), b.chars().collect());
    if a == b {
        return true;
    }
    if a.len().abs_diff(b.len()) > 1 {
        return false;
    }
    if a.len() == b.len() {
        let diff: Vec<usize> = (0..a.len()).filter(|&i| a[i] != b[i]).collect();
        if diff.len() == 2 && diff[1] == diff[0] + 1 {
            return a[diff[0]] == b[diff[1]] && a[diff[1]] == b[diff[0]];
        }
    }
    let (mut i, mut j, mut edits) = (0, 0, 0);
    while i < a.len() && j < b.len() {
        if a[i] == b[j] {
            i += 1;
            j += 1;
            continue;
        }
        edits += 1;
        if edits > 1 {
            return false;
        }
        if a.len() > b.len() {
            i += 1;
        } else if b.len() > a.len() {
            j += 1;
        } else {
            i += 1;
            j += 1;
        }
    }
    edits + (a.len() - i) + (b.len() - j) <= 1
}

fn word_score(e: &Entry, t: &str, fuzzy: bool) -> i64 {
    if e.name_words.iter().any(|w| w == t) {
        return 100;
    }
    if t.len() >= 2 && e.name_words.iter().any(|w| w.starts_with(t)) {
        return 60;
    }
    if e.tag_words.iter().any(|w| w == t) {
        return 50;
    }
    if t.len() >= 3 && e.tag_words.iter().any(|w| w.starts_with(t)) {
        return 30;
    }
    if fuzzy
        && t.len() >= 4
        && e.name_words
            .iter()
            .chain(&e.tag_words)
            .any(|w| w.len() >= 4 && one_edit(w, t))
    {
        return 20;
    }
    0
}

fn score(e: &Entry, tokens: &[String]) -> i64 {
    let mut total = 0;
    for t in tokens {
        let mut best = word_score(e, t, true) * 10;
        for s in PACK.synonyms.get(t).into_iter().flatten() {
            best = best.max(word_score(e, s, false) * 7);
        }
        if best == 0 {
            return 0;
        }
        total += best;
    }
    total + if e.featured { 150 } else { 0 } - e.name_words.len() as i64 * 10
}

/// The icons that best fit some words ("money", "invoice", "house"), best
/// first: `searchIcons` in agentKeySearch.ts, so the Chief and the picker
/// find the same. An id itself (featured, `lucide:…`, or a pack icon's bare
/// name) comes first.
pub fn find_icon(query: &str, limit: usize) -> Vec<String> {
    let q = query.trim().to_lowercase();
    let mut out = Vec::new();
    for exact in [q.clone(), format!("{}{q}", SPEC.pack.prefix)] {
        if is_icon(&exact) && !out.contains(&exact) {
            out.push(exact);
        }
    }
    let tokens = words_stemmed(&q);
    if tokens.is_empty() {
        return out;
    }
    let mut scored: Vec<(i64, &Entry)> = PACK
        .entries
        .iter()
        .map(|e| (score(e, &tokens), e))
        .filter(|(s, _)| *s > 0)
        .collect();
    scored.sort_by(|a, b| b.0.cmp(&a.0).then_with(|| a.1.id.cmp(&b.1.id)));
    for (_, e) in scored {
        if out.len() >= limit {
            break;
        }
        if !out.contains(&e.id) {
            out.push(e.id.clone());
        }
    }
    out.truncate(limit);
    out
}

/// "Blue", "Inbox": what a line in chat calls them.
pub fn colorway_name(id: &str) -> String {
    SPEC.colorways
        .iter()
        .find(|c| c.id == id)
        .map_or_else(|| id.to_string(), |c| c.name.clone())
}

/// A featured legend's name, or a pack icon's ("lucide:badge-dollar-sign" → "Badge dollar sign").
pub fn icon_name(id: &str) -> String {
    if let Some(i) = SPEC.icons.iter().find(|i| i.id == id) {
        return i.name.clone();
    }
    match id.strip_prefix(SPEC.pack.prefix.as_str()) {
        Some(name) => {
            let words = name.replace('-', " ");
            let mut chars = words.chars();
            chars.next().map_or_else(String::new, |c| {
                c.to_uppercase().collect::<String>() + chars.as_str()
            })
        }
        None => id.to_string(),
    }
}

/// The nearest colourway to an old avatar colour key (the first for one it doesn't know).
pub fn colorway_for_color(color: &str) -> String {
    let key = color.trim().to_ascii_lowercase();
    if is_colorway(&key) {
        return key;
    }
    SPEC.legacy_colors
        .get(&key)
        .cloned()
        .unwrap_or_else(|| SPEC.colorways[0].id.clone())
}

/// The old colour key written beside a colourway, for clients that only know colours.
pub fn legacy_color_for(colorway: &str) -> String {
    SPEC.colorways
        .iter()
        .find(|c| c.id == colorway)
        .map_or_else(|| "blue".to_string(), |c| c.legacy.clone())
}

fn words(text: &str) -> Vec<String> {
    text.to_lowercase()
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(str::to_string)
        .collect()
}

/// An icon read from the agent's name, then its role (`iconFor` in agentKeys.ts).
pub fn icon_for(name: &str, role: &str, is_main: bool) -> String {
    if is_main {
        return SPEC.chief_icon.clone();
    }
    for text in [name, role] {
        let ws = words(text);
        for rule in &SPEC.icon_rules {
            if ws.iter().any(|w| rule.words.contains(w)) {
                return rule.icon.clone();
            }
        }
    }
    SPEC.default_icon.clone()
}

/// One typed key as a bound key: a letter or digit, upper-cased.
pub fn normalize_bound_key(key: &str) -> Option<String> {
    let k = key.trim().to_ascii_uppercase();
    (k.chars().count() == 1 && SPEC.key_chars.contains(&k)).then_some(k)
}

/// The first key free for `name`: its own letters first, then every other one.
pub fn bound_key_for(name: &str, taken: &HashSet<String>) -> Option<String> {
    let upper = name.to_ascii_uppercase();
    upper
        .chars()
        .filter(|c| SPEC.key_chars.contains(*c))
        .chain(SPEC.key_chars.chars())
        .map(|c| c.to_string())
        .find(|c| !taken.contains(c))
}

/// A colourway for a key with `icon` that no one on the team already wears
/// with that icon: `preferred` when it's free, else the fewest-worn one that
/// is, so two agents never look the same (two blue speakers). `preferred`
/// when every colourway is taken with that icon.
pub fn distinct_colorway<'a>(
    preferred: &str,
    icon: &str,
    team: impl IntoIterator<Item = (&'a str, &'a str)> + Clone,
) -> String {
    let clash = |c: &str| team.clone().into_iter().any(|(w, i)| w == c && i == icon);
    if !clash(preferred) {
        return preferred.to_string();
    }
    let mut counts: Vec<(&str, usize)> = SPEC
        .colorways
        .iter()
        .map(|c| (c.id.as_str(), 0))
        .filter(|(id, _)| !clash(id))
        .collect();
    for (w, _) in team.clone() {
        if let Some(entry) = counts.iter_mut().find(|(id, _)| *id == w) {
            entry.1 += 1;
        }
    }
    counts
        .iter()
        .min_by_key(|(_, n)| *n)
        .map(|(id, _)| id.to_string())
        .unwrap_or_else(|| preferred.to_string())
}

/// The Chief's key before it was the app's mark: the star on Putty (its
/// "white"), what every Chief was given until then.
const PAST_CHIEF_ICON: &str = "star";
const PAST_CHIEF_COLORWAY: &str = "putty";

/// Set on the Chief once its key has been brought onto the current default
/// (`chief_key_default`), so a star the user picks later is never undone.
/// Kept in the agent's unknown fields, which older builds carry through.
pub const CHIEF_KEY_SETTLED: &str = "chiefKeyDefault";

/// The Chief's colourway (Graphite, the app icon's).
pub fn chief_colorway() -> &'static str {
    &SPEC.chief_colorway
}

/// Brings a Chief onto the current default key (one made by an older
/// build, or just made from its "white", which gives Putty): its
/// legend from the star to the app's mark and its colourway from Putty to
/// Graphite, each only when it is still the old default (no record says
/// whether the user chose it, so a value that differs is theirs and is
/// kept). Once only: marked `CHIEF_KEY_SETTLED` after. Returns whether
/// anything changed.
fn chief_key_default(a: &mut Agent) -> bool {
    if !a.is_main || a.extra.contains_key(CHIEF_KEY_SETTLED) {
        return false;
    }
    if a.icon.as_deref() == Some(PAST_CHIEF_ICON) {
        a.icon = Some(SPEC.chief_icon.clone());
    }
    if a.colorway.as_deref() == Some(PAST_CHIEF_COLORWAY) {
        // Its old `color` stays: the Chief's colour is the app's accent
        // (`src/lib/accent.ts`), and a new default key isn't a new accent.
        a.colorway = Some(SPEC.chief_colorway.clone());
    }
    a.extra
        .insert(CHIEF_KEY_SETTLED.into(), serde_json::Value::from(1));
    true
}

/// Gives every agent saved before keys a colourway (its colour's nearest),
/// an icon (from its name and role) and a key (the first free letter of its
/// name), the Chief first, then in team order; and keeps bound keys unique
/// (a later duplicate, say a restored agent's, gets a free one); and moves
/// a Chief still on the old default key onto the current one, once
/// (`chief_key_default`). Returns whether anything changed.
pub fn fill(agents: &mut [Agent]) -> bool {
    let mut changed = false;
    for i in 0..agents.len() {
        let a = &agents[i];
        let had_colorway = a.colorway.as_deref().is_some_and(is_colorway);
        let had_icon = a.icon.as_deref().is_some_and(is_icon);
        if had_colorway && had_icon {
            continue;
        }
        let icon = if had_icon {
            a.icon.clone().unwrap_or_default()
        } else {
            icon_for(&a.name, &a.role, a.is_main)
        };
        let colorway = if had_colorway {
            a.colorway.clone().unwrap_or_default()
        } else {
            // Not one someone chose: one no one else wears with this icon.
            let worn: Vec<(&str, &str)> = agents
                .iter()
                .enumerate()
                .filter(|(j, _)| *j != i)
                .filter_map(|(_, b)| Some((b.colorway.as_deref()?, b.icon.as_deref()?)))
                .collect();
            distinct_colorway(&colorway_for_color(&a.color), &icon, worn.iter().copied())
        };
        let a = &mut agents[i];
        a.colorway = Some(colorway);
        a.icon = Some(icon);
        changed = true;
    }
    // After the fill: a Chief saved before keys has just been given the old
    // colourway from its "white", and moves on with everyone else's.
    for a in agents.iter_mut() {
        changed |= chief_key_default(a);
    }
    let mut order: Vec<usize> = (0..agents.len()).collect();
    order.sort_by_key(|i| !agents[*i].is_main);
    let mut taken = HashSet::new();
    let mut missing = Vec::new();
    for i in order {
        match agents[i]
            .bound_key
            .as_deref()
            .and_then(normalize_bound_key)
            .filter(|k| !taken.contains(k))
        {
            Some(k) => {
                if agents[i].bound_key.as_deref() != Some(k.as_str()) {
                    agents[i].bound_key = Some(k.clone());
                    changed = true;
                }
                taken.insert(k);
            }
            None => missing.push(i),
        }
    }
    for i in missing {
        let key = bound_key_for(&agents[i].name, &taken);
        if let Some(k) = &key {
            taken.insert(k.clone());
        }
        if agents[i].bound_key != key {
            agents[i].bound_key = key;
            changed = true;
        }
    }
    changed
}

/// A change to an agent's key, checked: ids this build draws, and a bound
/// key no one else on the team has.
#[derive(Debug, Default, Clone, PartialEq)]
pub struct KeyChange {
    pub colorway: Option<String>,
    pub icon: Option<String>,
    pub bound_key: Option<String>,
}

impl KeyChange {
    pub fn is_empty(&self) -> bool {
        self.colorway.is_none() && self.icon.is_none() && self.bound_key.is_none()
    }

    /// Checks what was asked against `agent` (`None`: one being made) and
    /// its team, keeping only what differs.
    pub fn checked(
        agent: Option<&Agent>,
        team: &[Agent],
        colorway: Option<&str>,
        icon: Option<&str>,
        bound_key: Option<&str>,
    ) -> Result<KeyChange, String> {
        let mut out = KeyChange::default();
        if let Some(c) = colorway.map(|c| c.trim().to_ascii_lowercase()) {
            if !is_colorway(&c) {
                return Err(format!(
                    "There's no colourway called \"{c}\": {}.",
                    colorways().join(", ")
                ));
            }
            if agent.and_then(|a| a.colorway.as_deref()) != Some(c.as_str()) {
                out.colorway = Some(c);
            }
        }
        if let Some(asked) = icon.map(|i| i.trim().to_ascii_lowercase()) {
            // An id, or words for what it's for ("money", "invoice"): the best match.
            let Some(i) = find_icon(&asked, 1).into_iter().next() else {
                return Err(format!(
                    "No icon fits \"{asked}\". Try a plainer word for what it's for (\"money\", \"mail\", \"house\"), or one of: {}.",
                    icons().join(", ")
                ));
            };
            if agent.and_then(|a| a.icon.as_deref()) != Some(i.as_str()) {
                out.icon = Some(i);
            }
        }
        if let Some(raw) = bound_key {
            let Some(k) = normalize_bound_key(raw) else {
                return Err(format!(
                    "\"{}\" can't be a key: pick one letter or digit.",
                    raw.trim()
                ));
            };
            if let Some(other) = team.iter().find(|o| {
                agent.is_none_or(|a| a.id != o.id) && o.bound_key.as_deref() == Some(k.as_str())
            }) {
                return Err(format!(
                    "{k} is already {}'s key. Pick another, or change theirs first.",
                    other.name
                ));
            }
            if agent.and_then(|a| a.bound_key.as_deref()) != Some(k.as_str()) {
                out.bound_key = Some(k);
            }
        }
        Ok(out)
    }

    /// Applies it, keeping the old colour field near the colourway for clients that only read that.
    pub fn apply(&self, a: &mut Agent) {
        if let Some(c) = &self.colorway {
            a.colorway = Some(c.clone());
            a.color = legacy_color_for(c);
        }
        if let Some(i) = &self.icon {
            a.icon = Some(i.clone());
        }
        if let Some(k) = &self.bound_key {
            a.bound_key = Some(k.clone());
        }
    }

    /// "now Teal, with the Chat legend, on key Q", for a line in chat.
    pub fn line(&self) -> Option<String> {
        let mut parts = Vec::new();
        if let Some(c) = &self.colorway {
            parts.push(format!("now {}", colorway_name(c)));
        }
        if let Some(i) = &self.icon {
            parts.push(format!("with the {} legend", icon_name(i)));
        }
        if let Some(k) = &self.bound_key {
            parts.push(format!("on key {k}"));
        }
        if parts.is_empty() {
            return None;
        }
        let mut line = parts.join(", ");
        if self.colorway.is_none() {
            line = format!("now {line}");
        }
        Some(line)
    }
}
